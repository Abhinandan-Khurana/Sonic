#!/usr/bin/env python3
# Usage: scripts/launcher-monochrome.py app/src/main/res/drawable/ic_launcher_monochrome.xml preview.svg
# The themed (monochrome) launcher icon, drawn from the SONIC sleeve in one even-odd path:
# the disc is ink; dots and the line are holes inside it and ink outside it, like the sleeve.
import math, sys
K = 70 / 1254; O = 19.0
def X(x): return O + x * K
def dot(cx, cy, r): return f"M{cx-r:.2f},{cy:.2f}a{r:.2f},{r:.2f} 0 1,0 {2*r:.2f},0a{r:.2f},{r:.2f} 0 1,0 {-2*r:.2f},0z"
disc_c, disc_r = (X(622), X(595)), 462 * K
parts = [f"M{disc_c[0]-disc_r:.2f},{disc_c[1]:.2f}a{disc_r:.2f},{disc_r:.2f} 0 1,0 {2*disc_r:.2f},0a{disc_r:.2f},{disc_r:.2f} 0 1,0 {-2*disc_r:.2f},0z"]
def inside(x, y, pad=0): return math.hypot(x - disc_c[0], y - disc_c[1]) < disc_r - pad
# SONIC in a 5x7 dot face.
FONT = {
 'S': ["01111","10000","10000","01110","00001","00001","11110"],
 'O': ["11110","10001","10001","10001","10001","10001","11110"],
 'N': ["10001","11001","10101","10011","10001","10001","10001"],
 'I': ["11111","00100","00100","00100","00100","00100","11111"],
 'C': ["01111","10000","10000","10000","10000","10000","01111"],
}
pitch, dr = 1.12, 0.47
tx, ty = X(40), X(600) - 6 * pitch
text_box = (tx - 1, ty - 1, tx + 29 * pitch + 1, ty + 7 * pitch + 0.6)
for i, ch in enumerate("SONIC"):
    for row, bits in enumerate(FONT[ch]):
        for col, b in enumerate(bits):
            if b == "1":
                x, y = tx + (i * 6 + col) * pitch, ty + row * pitch
                parts.append(dot(x, y, dr))
# The arm's line under the word.
ly, lh = X(608) + 0.5, 0.5
parts.append(f"M{X(0):.2f},{ly:.2f}L{X(760):.2f},{ly:.2f}L{X(760):.2f},{ly+lh:.2f}L{X(0):.2f},{ly+lh:.2f}z")
# Grooves: rings drawn in toward a point right of centre, holes inside the disc.
def in_text(x, y): return text_box[0] - 0.4 < x < text_box[2] + 0.4 and text_box[1] - 0.4 < y < text_box[3] + 0.4
def ring(cx, cy, r, dotr, spacing, keep):
    n = max(8, int(2 * math.pi * r / spacing))
    for k in range(n):
        a = 2 * math.pi * k / n
        x, y = cx + r * math.cos(a), cy + r * math.sin(a)
        if keep(x, y) and not in_text(x, y) and not (abs(y - (ly + lh / 2)) < 0.9 and x < X(760) + 0.5):
            parts.append(dot(x, y, dotr))
inner = 5
for i in range(inner):
    t = i / (inner - 1)
    cx = X(880 + (725 - 880) * t); r = (95 + (365 - 95) * t) * K
    ring(cx, disc_c[1], r, 0.46, 1.9, lambda x, y: inside(x, y, 0.8))
# Two rings outside the disc on the right, ink dots.
for cx, r in ((X(650), 520 * K), (X(640), 585 * K)):
    ring(cx, disc_c[1], r, 0.5, 2.0, lambda x, y: math.hypot(x - disc_c[0], y - disc_c[1]) > disc_r + 1.0 and x > disc_c[0])
path = "".join(parts)
xml = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Themed icons (Android 13+): the SONIC sleeve in one tone. The disc is ink; its grooves, the
     dotted word and the arm's line are cut out of it, and stay ink where they leave the disc.
     Generated by scripts/launcher-monochrome.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path
        android:fillColor="#FF000000"
        android:fillType="evenOdd"
        android:pathData="{path}" />
</vector>
'''
svg = f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="864" height="864"><rect width="108" height="108" fill="#1f2433"/><circle cx="54" cy="54" r="36" fill="#d6dcf5"/><path fill="#2c3550" fill-rule="evenodd" d="{path}"/></svg>'
open(sys.argv[1], "w").write(xml); open(sys.argv[2], "w").write(svg)
print(len(parts), "shapes", len(path), "chars")
